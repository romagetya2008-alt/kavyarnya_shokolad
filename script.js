// =====================================
// ВІДКРИТТЯ ТОВАРУ
// =====================================

function openProduct(product) {

    if (!products[product]) {
        return;
    }

    $("#product-content").html(
        products[product]
    );

    $("#product-modal")
        .css("display", "flex");

    $("body").css("overflow", "hidden");
}



// =====================================
// ЗАКРИТТЯ ТОВАРУ
// =====================================

function closeProduct() {

    $("#product-modal").fadeOut(200);

    $("body").css("overflow", "auto");
}



// =====================================
// КЛІК ПО ТЕМНОМУ ФОНУ
// =====================================

$("#product-modal").click(function(e) {

    if (e.target === this) {

        closeProduct();

    }

});



// =====================================
// ESC — ЗАКРИТИ МОДАЛКУ
// =====================================

$(document).keydown(function(e) {

    if (e.key === "Escape") {

        closeProduct();

    }

});



// =====================================
// ТІНЬ NAVBAR ПРИ СКРОЛІ
// =====================================

$(window).scroll(function() {

    if ($(window).scrollTop() > 50) {

        $(".navbar").css(
            "box-shadow",
            "0 8px 25px rgba(0,0,0,.15)"
        );

    } else {

        $(".navbar").css(
            "box-shadow",
            "0 3px 20px rgba(0,0,0,.08)"
        );

    }

});



// =====================================
// АНІМАЦІЯ КАРТОК
// =====================================

function showCards() {

    $(".menu-card").each(function(index) {

        var card = $(this);

        var cardTop = card.offset().top;

        var windowBottom =
            $(window).scrollTop() +
            $(window).height();


        if (
            cardTop <
            windowBottom - 50
        ) {

            setTimeout(function() {

                card.addClass("show");

            }, index * 100);

        }

    });

}



// =====================================
// ЗАПУСК АНІМАЦІЇ
// =====================================

$(window).on(
    "scroll",
    showCards
);


$(document).ready(function() {

    showCards();

});